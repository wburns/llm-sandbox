#!/usr/bin/env bash
# common-sandbox.sh - Shared engine for ephemeral AI containers with Git Worktrees
# Source it from an agent launcher, or run it directly (common-sandbox --prune|--clean).

set -e

# --- 1. Base Shared Paths ---
export BASE_SANDBOX_DIR="${BASE_SANDBOX_DIR:-$HOME/.local/share/llm_sandbox_homes}"
export SHARED_M2_DIR="$BASE_SANDBOX_DIR/shared_m2/repository"
export WORKTREES_BASE_DIR="$BASE_SANDBOX_DIR/worktrees"
# Logseq run logs written by logseq-tracker. Kept outside BASE_SANDBOX_DIR so
# --clean / --prune never delete them. Each session writes into its own
# subdirectory (see init_worktree_environment); when the session ends the logs
# are appended to the Logseq graph at LOGSEQ_GRAPH_DIR (skipped if it doesn't exist).
export LOGSEQ_LOG_DIR="${LOGSEQ_LOG_DIR:-$HOME/.local/share/llm-sandbox-logs}"
export LOGSEQ_GRAPH_DIR="${LOGSEQ_GRAPH_DIR:-$HOME/Documents/Logseq}"
_COMMON_SANDBOX_DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
# Container runtime (podman or docker), picked when a session starts.
source "$_COMMON_SANDBOX_DIR/../backend/selector.sh"  # (bin/ and backend/ are siblings)

# --- 2. Maintenance Flags ---
handle_maintenance_flags() {
    local action="$1"
    if [[ "$action" == "--clean" ]]; then
        echo "🧹 Wiping all sandbox environments, caches, and worktrees..."
        rm -rf "${BASE_SANDBOX_DIR:?}"/*
        git worktree prune 2>/dev/null || true
        echo "Done."
        exit 0
    elif [[ "$action" == "--prune" ]]; then
        echo "🧹 Pruning sandbox caches and Maven dependencies older than 14 days..."
        if [ -d "$BASE_SANDBOX_DIR" ]; then
            find "$BASE_SANDBOX_DIR" -type f -atime +14 -delete 2>/dev/null || \
            find "$BASE_SANDBOX_DIR" -type f -mtime +14 -delete 2>/dev/null || true
            find "$BASE_SANDBOX_DIR" -type d -empty -delete 2>/dev/null || true
        fi
        git worktree prune 2>/dev/null || true
        echo "Done."
        exit 0
    fi
}

# --- 2b. Rule Compilation ---
# The rules/ and skills/ shipped with llm-sandbox live next to bin/ (in the
# install dir, or the repo when run from a checkout). Sessions are always seeded
# with them; the agent's own config dir (e.g. ~/.claude) is layered on top, so a
# file there with the same name wins. This works with or without
# `install.sh --no-agent-config`.
SHIPPED_RULES_DIR="$_COMMON_SANDBOX_DIR/../rules"
SHIPPED_SKILLS_DIR="$_COMMON_SANDBOX_DIR/../skills"

# seed_shipped <rules|skills> <dest_dir>
# Copies the contents of the shipped rules/ or skills/ directory into <dest_dir>.
seed_shipped() {
    local src="$SHIPPED_RULES_DIR"
    [ "$1" = skills ] && src="$SHIPPED_SKILLS_DIR"
    [ -d "$src" ] || return 0
    mkdir -p "$2"
    cp -aL "$src/." "$2/"
}

# compile_rules <output_file> <rules_dir>...
# Concatenates every *.md / *.txt file in the <rules_dir>s (symlinked dirs and
# files are fine) into <output_file>, the initial-context file that Claude
# (CLAUDE.md) and Gemini (GEMINI.md) read on startup. A rule file with the same
# name in a later <rules_dir> replaces the earlier one. The output file is
# regenerated on every launch, so don't hand-edit it; put rules in a
# <rules_dir> instead. Does nothing if there are no rule files, leaving
# <output_file> as is.
compile_rules() {
    local output_file="$1"
    shift
    local rules_dir rule name
    local -A by_name=()
    local rules=()

    for rules_dir in "$@"; do
        for rule in "$rules_dir"/*.md "$rules_dir"/*.txt; do
            [ -f "$rule" ] && by_name["$(basename "$rule")"]="$rule"
        done
    done
    while IFS= read -r name; do
        [ -n "$name" ] && rules+=("${by_name[$name]}")
    done < <(printf '%s\n' "${!by_name[@]}" | sort)
    [ "${#rules[@]}" -gt 0 ] || return 0

    echo "📜 Generating $output_file from ${#rules[@]} rule file(s)..."
    {
        echo "<!-- Generated by llm-sandbox from: $* . Edit the rule files, not this file. -->"
        echo
        for rule in "${rules[@]}"; do
            printf '<!-- Rule Source: %s -->\n\n' "$(basename "$rule")"
            cat "$rule"
            printf '\n\n---\n\n'
        done
    } > "$output_file"
}

# --- 2c. Host Config Seeding ---
# seed_from_host <host_dir> <dest_dir> <item>...
# Copies the named files/directories that exist under <host_dir> into <dest_dir>
# (inside the per-session home that is mounted as /root). Nothing from the host
# is bind-mounted, so the agent can't modify or relabel the host's config and
# everything it writes stays in the session home. Missing items are skipped.
seed_from_host() {
    local host_dir="$1" dest_dir="$2"
    shift 2
    local item
    mkdir -p "$dest_dir"
    for item in "$@"; do
        [ -e "$host_dir/$item" ] && cp -aL "$host_dir/$item" "$dest_dir/"
    done
    return 0
}

# --- 2d. Persistent Auth (copy in, sync back on exit) ---
# Login/credential files are copied into the session home like everything else,
# but when the session ends any file the agent changed or created is written
# back to the host, so a login made in the sandbox persists between runs.
# Nothing is bind-mounted, and concurrent sessions never share a live file.
AUTH_SYNC_HOST=()      # host path of each tracked file
AUTH_SYNC_SESSION=()   # matching path inside the session home
AUTH_SYNC_BASELINE=()  # sha256 of the host file at launch ("absent" if missing)

_file_hash() {
    if [ ! -f "$1" ]; then
        echo absent
    elif command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1  # older macOS has no sha256sum
    fi
}

# seed_auth_from_host <host_dir> <dest_dir> <item>...
# Like seed_from_host, but also records each file (even ones that don't exist
# on the host yet) so _sync_auth_back can persist changes at exit. Files only.
seed_auth_from_host() {
    local host_dir="$1" dest_dir="$2"
    shift 2
    local item
    mkdir -p "$dest_dir"
    for item in "$@"; do
        AUTH_SYNC_HOST+=("$host_dir/$item")
        AUTH_SYNC_SESSION+=("$dest_dir/$item")
        AUTH_SYNC_BASELINE+=("$(_file_hash "$host_dir/$item")")
        [ -f "$host_dir/$item" ] && cp -aL "$host_dir/$item" "$dest_dir/"
    done
    return 0
}

# _sync_auth_back
# For every tracked file that differs from its launch-time baseline, write it
# back to the host (atomically; mode preserved, 600 for new files). If the host
# copy also changed meanwhile (e.g. another session refreshed the token), the
# newer file by mtime wins. Called from the exit trap.
_sync_auth_back() {
    local i host session base session_hash host_hash target tmp
    for i in "${!AUTH_SYNC_HOST[@]}"; do
        host="${AUTH_SYNC_HOST[$i]}"
        session="${AUTH_SYNC_SESSION[$i]}"
        base="${AUTH_SYNC_BASELINE[$i]}"

        [ -f "$session" ] || continue
        session_hash="$(_file_hash "$session")"
        [ "$session_hash" = "$base" ] && continue

        host_hash="$(_file_hash "$host")"
        [ "$host_hash" = "$session_hash" ] && continue
        if [ "$host_hash" != "$base" ] && ! [ "$session" -nt "$host" ]; then
            echo "⚠️ $host changed on the host during the session and is newer; not overwriting."
            continue
        fi

        # Write through a symlinked host file. (readlink -f, unlike GNU's -m, exists
        # on macOS too; it can fail there when the file doesn't exist yet.)
        target="$(readlink -f "$host" 2>/dev/null)" || target="$host"
        mkdir -p "$(dirname "$target")"
        tmp="$(mktemp "$target.XXXXXX")" || continue
        if cp "$session" "$tmp"; then
            if [ -f "$target" ]; then
                # Keep the host file's mode (GNU stat, else BSD/macOS stat)
                chmod "$(stat -c '%a' "$target" 2>/dev/null || stat -f '%Lp' "$target")" "$tmp"
            else
                chmod 600 "$tmp"
            fi
            mv -f "$tmp" "$target" && echo "🔑 Saved updated $host from the session."
        else
            rm -f "$tmp"
        fi
    done
    return 0
}

# --- 2e. Logseq Log Sync ---
# _sync_logseq_logs
# Appends every run log this session's logseq-tracker wrote ($SESSION_LOG_DIR/run_*.md)
# to the journal page of the day the run started, <graph>/journals/YYYY_MM_DD.md
# (created if missing). A log is identified by its "id::" property: if that id is
# already in the journal the log was synced before and is left alone, so running
# this twice never duplicates anything. Called from the exit trap, after the
# container has ended. The raw logs stay in $SESSION_LOG_DIR as an archive.
_sync_logseq_logs() {
    [ -n "$SESSION_LOG_DIR" ] && [ -d "$SESSION_LOG_DIR" ] || return 0
    local logs=() log
    for log in "$SESSION_LOG_DIR"/run_*.md; do
        [ -f "$log" ] && logs+=("$log")
    done
    if [ "${#logs[@]}" -eq 0 ]; then
        rmdir "$SESSION_LOG_DIR" 2>/dev/null || true
        return 0
    fi

    if [ ! -d "$LOGSEQ_GRAPH_DIR" ]; then
        echo "⚠️ Logseq graph $LOGSEQ_GRAPH_DIR not found (set LOGSEQ_GRAPH_DIR); logs kept in $SESSION_LOG_DIR."
        return 0
    fi

    local id day journal
    for log in "${logs[@]}"; do
        id="$(sed -n 's/^  id:: //p' "$log" | head -n 1)"
        day="$(basename "$log" | sed -n 's/.*_\([0-9]\{4\}\)\([0-9]\{2\}\)\([0-9]\{2\}\)-[0-9]\{6\}\.md$/\1_\2_\3/p')"
        [ -n "$day" ] || day="$(date +%Y_%m_%d)"
        journal="$LOGSEQ_GRAPH_DIR/journals/$day.md"

        if [ -n "$id" ] && [ -f "$journal" ] && grep -qF "id:: $id" "$journal"; then
            echo "📝 $(basename "$log") is already in $journal"
            continue
        fi
        mkdir -p "$LOGSEQ_GRAPH_DIR/journals"
        # Start on a fresh line if the journal doesn't end with a newline
        if [ -s "$journal" ] && [ -n "$(tail -c 1 "$journal")" ]; then
            echo >> "$journal"
        fi
        if cat "$log" >> "$journal"; then
            echo "📝 Appended $(basename "$log") to $journal"
        else
            echo "⚠️ Could not append $log to $journal"
        fi
    done
    return 0
}

# --- 3. Worktree & Workspace Initialization ---
init_worktree_environment() {
    local agent_prefix="${1:-agent}"

    if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        echo "ERROR: Current directory is not inside a Git repository." >&2
        exit 1
    fi

    # Fail before creating the worktree if no container runtime is usable
    select_backend || exit 1

    MAIN_REPO_DIR="$(git rev-parse --show-toplevel)"
    COMMON_GIT_DIR="$(git rev-parse --git-common-dir)"
    COMMON_GIT_DIR="$(cd "$COMMON_GIT_DIR" && pwd)"

    CURRENT_BRANCH="$(git rev-parse --abbrev-ref HEAD)"
    INITIAL_COMMIT="$(git rev-parse HEAD)"

    SESSION_ID="${$}_$(date +%s)"
    WORKTREE_NAME="${agent_prefix}_${CURRENT_BRANCH//\//_}_${SESSION_ID}"
    WORKTREE_DIR="$WORKTREES_BASE_DIR/$WORKTREE_NAME"
    TEMP_BRANCH="${agent_prefix}-session/${CURRENT_BRANCH//\//-}/${SESSION_ID}"

    SANDBOX_HOME="$BASE_SANDBOX_DIR/sessions/${agent_prefix}_${SESSION_ID}"
    CONTAINER_NAME="${agent_prefix}_${SESSION_ID}"
    SESSION_LOG_DIR="$LOGSEQ_LOG_DIR/$CONTAINER_NAME"
    SESSION_CREATED_AT="$(date +'%Y-%m-%d %H:%M:%S')"
    AGENT_PREFIX="$agent_prefix"

    mkdir -p "$SANDBOX_HOME" "$SHARED_M2_DIR" "$WORKTREES_BASE_DIR"
    _save_session_metadata "active"

    echo "🌿 Creating worktree at $WORKTREE_DIR based on '$CURRENT_BRANCH'..."
    git worktree add -b "$TEMP_BRANCH" "$WORKTREE_DIR" HEAD

    # A caller (review-pr) can set SANDBOX_RESTORE_REF to have the main repo switched
    # back to that branch/commit now that the worktree exists, before the agent starts.
    if [ -n "${SANDBOX_RESTORE_REF:-}" ]; then
        echo "↩️ Switching '$MAIN_REPO_DIR' back to '$SANDBOX_RESTORE_REF'..."
        git -C "$MAIN_REPO_DIR" checkout -q "$SANDBOX_RESTORE_REF" ||
            echo "⚠️ Could not switch back to '$SANDBOX_RESTORE_REF'; '$MAIN_REPO_DIR' remains on '$CURRENT_BRANCH'." >&2
    fi

    # Register exit and interrupt hook
    trap _cleanup_and_merge_prompt EXIT INT TERM
}

# --- 3b. Worktree Initialization for Resumed Sessions ---
init_resume_environment() {
    local session_home="$1"
    local agent_prefix="$2"

    if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        echo "ERROR: Current directory is not inside a Git repository." >&2
        exit 1
    fi

    MAIN_REPO_DIR="$(git rev-parse --show-toplevel)"
    COMMON_GIT_DIR="$(git rev-parse --git-common-dir)"
    COMMON_GIT_DIR="$(cd "$COMMON_GIT_DIR" && pwd)"

    CURRENT_BRANCH="$(git rev-parse --abbrev-ref HEAD)"
    INITIAL_COMMIT="$(git rev-parse HEAD)"

    AGENT_PREFIX="$agent_prefix"
    SESSION_ID="${$}_$(date +%s)"
    WORKTREE_NAME="${agent_prefix}_resume_${CURRENT_BRANCH//\//_}_${SESSION_ID}"
    WORKTREE_DIR="$WORKTREES_BASE_DIR/$WORKTREE_NAME"
    TEMP_BRANCH="${agent_prefix}-resume/${CURRENT_BRANCH//\//-}/${SESSION_ID}"

    SANDBOX_HOME="$session_home"
    CONTAINER_NAME="${agent_prefix}_resume_${SESSION_ID}"
    SESSION_LOG_DIR="$LOGSEQ_LOG_DIR/$CONTAINER_NAME"

    if [ -f "$SANDBOX_HOME/.session-info" ]; then
        SESSION_CREATED_AT="$(sed -n 's/^CREATED_AT=//p' "$SANDBOX_HOME/.session-info" | head -n 1)"
        # The session's own base branch must survive a resume: CURRENT_BRANCH is
        # just whatever is checked out now, and only applies to this resumed run.
        SESSION_BASE_BRANCH="$(sed -n 's/^BASE_BRANCH=//p' "$SANDBOX_HOME/.session-info" | head -n 1)"
    fi
    [ -n "${SESSION_CREATED_AT:-}" ] || SESSION_CREATED_AT="$(date +'%Y-%m-%d %H:%M:%S')"

    mkdir -p "$SANDBOX_HOME" "$SHARED_M2_DIR" "$WORKTREES_BASE_DIR"

    echo "🌿 Creating worktree at $WORKTREE_DIR based on '$CURRENT_BRANCH' for resume..."
    git worktree add -b "$TEMP_BRANCH" "$WORKTREE_DIR" HEAD

    _save_session_metadata "resumed"

    # Register exit and interrupt hook
    trap _cleanup_and_merge_prompt EXIT INT TERM
}

# _save_session_metadata <status>
# Saves or updates .session-info inside $SANDBOX_HOME for sandbox-resume discovery.
_save_session_metadata() {
    local status="${1:-active}"
    [ -n "${SANDBOX_HOME:-}" ] || return 0
    mkdir -p "$SANDBOX_HOME"
    cat > "$SANDBOX_HOME/.session-info" <<EOF
AGENT=${AGENT_PREFIX:-${agent_prefix:-agent}}
SESSION_ID=${SESSION_ID:-}
CONTAINER_NAME=${CONTAINER_NAME:-}
REPO_DIR=${MAIN_REPO_DIR:-}
REPO_NAME=$(basename "${MAIN_REPO_DIR:-unknown}")
BASE_BRANCH=${SESSION_BASE_BRANCH:-${CURRENT_BRANCH:-}}
INITIAL_COMMIT=${INITIAL_COMMIT:-}
CREATED_AT=${SESSION_CREATED_AT:-$(date +'%Y-%m-%d %H:%M:%S')}
UPDATED_AT=$(date +'%Y-%m-%d %H:%M:%S')
STATUS=$status
${INITIAL_PROMPT:+INITIAL_PROMPT=${INITIAL_PROMPT//$'\n'/ }}
EOF
}

# --- 4. Interactive Exit & Merge Trap Handler ---
_cleanup_and_merge_prompt() {
    set +e
    _sync_auth_back
    _sync_logseq_logs

    echo ""
    echo "🔍 Checking for work done in session..."

    # Auto-commit dirty worktree changes so uncommitted edits aren't lost
    if [ -d "$WORKTREE_DIR" ] && [ -n "$(git -C "$WORKTREE_DIR" status --porcelain 2>/dev/null)" ]; then
        echo "📦 Auto-committing uncommitted session changes..."
        git -C "$WORKTREE_DIR" add -A
        git -C "$WORKTREE_DIR" commit -m "chore: snapshot uncommitted session changes" >/dev/null 2>&1 || true
    fi

    SESSION_COMMIT=$(git rev-parse "$TEMP_BRANCH" 2>/dev/null || echo "$INITIAL_COMMIT")
    local keep_branch=false

    if [ "$INITIAL_COMMIT" != "$SESSION_COMMIT" ]; then
        echo ""
        echo "💡 Agent made commits on branch: $TEMP_BRANCH"
        git -C "$MAIN_REPO_DIR" log --oneline "${INITIAL_COMMIT}..${SESSION_COMMIT}"
        echo ""

        if [ "${SANDBOX_NON_INTERACTIVE:-}" = 1 ]; then
            # Unattended run (e.g. review-pr --non-interactive): nobody to ask, never merge.
            ACTION=n
        else
            read -r -p "👉 Merge changes back into '$CURRENT_BRANCH'? [Y: merge (default) / k: keep branch / n: discard]: " ACTION </dev/tty
        fi

        case "$ACTION" in
            ""|[yY][eE][sS]|[yY])
                # 'git merge' merges into whatever is checked out. If the main repo has
                # moved to another branch, switch back to the original branch (only when
                # there are no working changes), merge, then return to where it was.
                local now_branch return_ref=""
                now_branch="$(git -C "$MAIN_REPO_DIR" rev-parse --abbrev-ref HEAD 2>/dev/null)"
                if [ "$now_branch" != "$CURRENT_BRANCH" ]; then
                    if [ -n "$(git -C "$MAIN_REPO_DIR" status --porcelain 2>/dev/null)" ]; then
                        echo "⚠️ '$MAIN_REPO_DIR' is now on '$now_branch', not '$CURRENT_BRANCH', and has working changes. Not merging."
                        echo "   Check out '$CURRENT_BRANCH' and run: git merge $TEMP_BRANCH"
                        echo "📌 Branch preserved: $TEMP_BRANCH"
                        keep_branch=true
                        now_branch=""
                    else
                        # Detached HEAD reports "HEAD"; return to the commit in that case
                        if [ "$now_branch" = "HEAD" ]; then
                            return_ref="$(git -C "$MAIN_REPO_DIR" rev-parse HEAD)"
                        else
                            return_ref="$now_branch"
                        fi
                        echo "🔀 '$MAIN_REPO_DIR' is on '$now_branch'; temporarily checking out '$CURRENT_BRANCH'..."
                        if ! git -C "$MAIN_REPO_DIR" checkout "$CURRENT_BRANCH"; then
                            echo "⚠️ Could not check out '$CURRENT_BRANCH'. Not merging."
                            echo "   Check out '$CURRENT_BRANCH' and run: git merge $TEMP_BRANCH"
                            echo "📌 Branch preserved: $TEMP_BRANCH"
                            keep_branch=true
                            now_branch=""
                            return_ref=""
                        fi
                    fi
                fi

                if [ -n "$now_branch" ]; then
                    echo "🔀 Merging $TEMP_BRANCH into $CURRENT_BRANCH..."
                    if git -C "$MAIN_REPO_DIR" merge --no-edit "$TEMP_BRANCH"; then
                        echo "✅ Successfully merged!"
                    else
                        echo "⚠️ Merge conflict encountered! Aborted merge. Branch '$TEMP_BRANCH' kept."
                        git -C "$MAIN_REPO_DIR" merge --abort 2>/dev/null || true
                        keep_branch=true
                    fi

                    if [ -n "$return_ref" ]; then
                        echo "↩️ Switching '$MAIN_REPO_DIR' back to '$now_branch'..."
                        git -C "$MAIN_REPO_DIR" checkout "$return_ref" ||
                            echo "⚠️ Could not switch back to '$now_branch'; '$MAIN_REPO_DIR' remains on '$CURRENT_BRANCH'."
                    fi
                fi
                ;;
            [kK][eE][eE][pP]*|[kK])
                echo "📌 Branch preserved: $TEMP_BRANCH"
                keep_branch=true
                ;;
            *)
                echo "🗑️ Discarding session branch."
                ;;
        esac
    else
        echo "ℹ️ No changes made during this session."
    fi

    echo "🧹 Removing worktree..."
    if [ -d "$WORKTREE_DIR" ]; then
        git worktree remove --force "$WORKTREE_DIR" 2>/dev/null || rm -rf "$WORKTREE_DIR"
        git worktree prune 2>/dev/null || true
    fi

    if [ "$keep_branch" = false ]; then
        git -C "$MAIN_REPO_DIR" branch -D "$TEMP_BRANCH" 2>/dev/null || true
    fi

    _save_session_metadata "closed"
    echo "✨ Session cleanup finished."
}

# --- 5. Container Execution ---
# run_agent_container <image> [run options...] [-- command [args...]]
# Everything before "--" is passed to `podman run` / `docker run` (see
# backend/selector.sh) as options. Everything after it is the command run inside
# the container (it must come *after* the image name, so it is placed there
# here). With no command the image's CMD runs.
run_agent_container() {
    local image_name="$1"
    shift
    local extra_args=() container_cmd=()
    while [ "$#" -gt 0 ]; do
        if [ "$1" = "--" ]; then
            shift
            container_cmd=("$@")
            break
        fi
        extra_args+=("$1")
        shift
    done

    # Git configuration
    seed_from_host "$HOME" "$SANDBOX_HOME" .gitconfig
    seed_from_host "$HOME/.config" "$SANDBOX_HOME/.config" git

    HOST_GH_TOKEN=$(gh auth token 2>/dev/null || true)

    # logseq-tracker: mount the installed copy read-only (never one found in the
    # project being worked on) and this session's host directory for its logs.
    local tracker_path="$_COMMON_SANDBOX_DIR/../share/logseq-tracker"  # (bin/ and share/ are siblings)
    if [ ! -f "$tracker_path" ]; then
        echo "ERROR: $tracker_path not found; reinstall llm-sandbox." >&2
        exit 1
    fi
    mkdir -p "$SESSION_LOG_DIR"

    # Base flags shared across all tools. An unattended run (SANDBOX_NON_INTERACTIVE=1)
    # gets no tty or stdin, so it works from scripts and in parallel.
    local tty_flags=(-it)
    [ "${SANDBOX_NON_INTERACTIVE:-}" = 1 ] && tty_flags=()
    local base_flags=(
        --rm "${tty_flags[@]}"
        --name "$CONTAINER_NAME"
        --label "llm-sandbox.branch=$TEMP_BRANCH"
        --label "llm-sandbox.base-branch=$CURRENT_BRANCH"
        --network host
        --tz=local
        -e TERM="${TERM:-xterm-256color}"
        -e COLORTERM="${COLORTERM:-truecolor}"
        -v "$WORKTREE_DIR":/workspace:Z
        -v "$COMMON_GIT_DIR":"$COMMON_GIT_DIR":z
        -v "$SANDBOX_HOME":/root:Z
        -v "$SHARED_M2_DIR":/root/.m2/repository:z
        -v "$tracker_path":/usr/local/bin/logseq-tracker:ro,z
        -v "$SESSION_LOG_DIR":/logseq-logs:z
        -e LOGSEQ_LOG_DIR=/logseq-logs
    )

    # Forwarded by name (value taken from this process's environment), so the
    # token never appears on the podman/docker command line or in `ps`.
    if [ -n "$HOST_GH_TOKEN" ]; then
        export GH_TOKEN="$HOST_GH_TOKEN"
        base_flags+=(--env GH_TOKEN)
    fi

    echo "🚀 Launching container [$CONTAINER_NAME]..."
    echo "📂 Workspace: $WORKTREE_DIR -> /workspace"
    echo "☕ Maven cache: $SHARED_M2_DIR -> /root/.m2/repository"
    echo "📝 Logseq logs: $SESSION_LOG_DIR -> /logseq-logs (synced to $LOGSEQ_GRAPH_DIR on exit)"
    select_backend || exit 1  # (already done by init_worktree_environment)
    echo "📦 Container backend: $SANDBOX_BACKEND"
    backend_preflight
    adapt_run_options "${base_flags[@]}" "${extra_args[@]}"
    backend_cli run "${ADAPTED_RUN_OPTIONS[@]}" "$image_name" "${container_cmd[@]}"
}

# --- 6. Direct Invocation (maintenance entry point) ---
# When executed rather than sourced, e.g. `common-sandbox --prune` from the
# startup service, only the agent-agnostic maintenance flags are available.
if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
    case "${1:-}" in
        --clean|--prune)
            handle_maintenance_flags "$1"
            ;;
        *)
            echo "Usage: $(basename "$0") --prune | --clean" >&2
            echo "  --prune  Remove sandbox cache files older than 14 days" >&2
            echo "  --clean  Wipe all sandbox environments, caches and worktrees" >&2
            exit 1
            ;;
    esac
fi
